//! `inno docs` — generate documentation from source code.
//!
//! Scans a directory for Rust source files and generates markdown
//! documentation from public items and their doc comments.

use crate::errors::InnoframeworkCliError;
use innoframework_docs_gen::{generate_docs, render_markdown};
use std::fs;
use std::path::Path;

/// Run the docs generator.
pub fn run(
    source_dir: Option<String>,
    output: Option<String>,
) -> Result<(), InnoframeworkCliError> {
    let source_dir = source_dir.unwrap_or_else(|| ".".to_string());
    let root = Path::new(&source_dir);

    if !root.exists() {
        return Err(InnoframeworkCliError::new(
            crate::errors::CliErrorCode::TemplateMissing,
            format!("source directory '{source_dir}' does not exist"),
            "check the path and try again",
            None,
        ));
    }

    let doc_output = generate_docs(root).map_err(|e| {
        InnoframeworkCliError::new(
            crate::errors::CliErrorCode::TemplateMissing,
            format!("cannot generate docs: {e}"),
            "check that the directory contains Rust source files",
            None,
        )
    })?;

    let markdown = render_markdown(&doc_output.items, &doc_output.module_name);

    let header = format!(
        "# {}\n\nGenerated by `inno docs`. This document is produced from source code comments.\n\n",
        doc_output.module_name
    );
    let full = format!("{}{}", header, markdown);

    match output {
        Some(path) => {
            fs::write(&path, &full).map_err(|e| {
                InnoframeworkCliError::new(
                    crate::errors::CliErrorCode::TemplateMissing,
                    format!("cannot write docs to '{path}': {e}"),
                    "check disk space and permissions",
                    None,
                )
            })?;
            println!("inno docs: written to '{}'", path);
        }
        None => {
            print!("{full}");
        }
    }

    Ok(())
}
